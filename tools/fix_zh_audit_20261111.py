def norm(s):
    return re.sub(r'[^\u4e00-\u9fffA-Za-z0-9]', '', s or '')

def kws(s):
    return [w for w in re.split(r'[^\u4e00-\u9fffA-Za-z0-9]+', s) if len(w) >= 2]

def d2dt(s):
    try: return datetime.strptime(str(s)[:10], '%Y-%m-%d').date()
    except: return None

